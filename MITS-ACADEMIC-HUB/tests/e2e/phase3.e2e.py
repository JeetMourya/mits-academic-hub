import json
from playwright.sync_api import sync_playwright
BASE = 'http://localhost:3111'
VIEWS = [('1920', 1920, 1080), ('1366', 1366, 768), ('1280', 1280, 720), ('tablet768', 768, 1024), ('mobile390', 390, 844), ('mobile360', 360, 800)]
res = []


def check(name, ok, detail=''):
    res.append((name, bool(ok), str(detail)))
    print(('PASS' if ok else 'FAIL'), name, str(detail)[:140], flush=True)


HOOK = """
window.__cap=[];
const _clear=CanvasRenderingContext2D.prototype.clearRect;
CanvasRenderingContext2D.prototype.clearRect=function(...a){window.__cap=[];return _clear.apply(this,a)};
const _ft=CanvasRenderingContext2D.prototype.fillText;
CanvasRenderingContext2D.prototype.fillText=function(t,...a){window.__cap.push(t);return _ft.call(this,t,...a)};
"""
with sync_playwright() as p:
    b = p.chromium.launch()
    for name, w, h in VIEWS:
        ctx = b.new_context(viewport={'width': w, 'height': h})
        pg = ctx.new_page()
        errs = []
        pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' and 'fonts.g' not in m.text and 'ERR_' not in m.text and 'Failed to load resource' not in m.text else None)
        pg.goto(BASE + '/', wait_until='load')
        pg.add_style_tag(content='html{scroll-behavior:auto!important}')
        pg.wait_for_timeout(500)
        ov = pg.evaluate('document.documentElement.scrollWidth - document.documentElement.clientWidth')
        check(f'no horizontal overflow @{name}', ov <= 0, f'overflow={ov}')
        wide = pg.evaluate("""[...document.querySelectorAll('main *, header *, footer *')].filter(e=>{const r=e.getBoundingClientRect();return r.width>0&&r.right>innerWidth+1&&getComputedStyle(e).position!=='absolute'&&!e.closest('.tool-tabs,.table-wrap,table')}).slice(0,3).map(e=>e.tagName+'.'+e.className)""")
        check(f'no element past viewport @{name}', not wide, wide)
        check(f'no console/page errors @{name}', not errs, errs[:2])
        pg.screenshot(path=f'/home/claude/shots/home-{name}.png')
        pg.evaluate("document.getElementById('lookup').scrollIntoView()")
        pg.wait_for_timeout(250)
        pg.screenshot(path=f'/home/claude/shots/verify-{name}.png')
        ctx.close()

    ctx = b.new_context(viewport={'width': 1366, 'height': 768})
    ctx.add_init_script(HOOK)
    pg = ctx.new_page()
    posts = []
    pg.on('request', lambda r: posts.append(r.post_data) if r.method == 'POST' and '/api/results/fetch' in r.url else None)
    pg.goto(BASE + '/')
    pg.wait_for_timeout(400)
    check('title is new brand', 'MITS Marksheet Verification' in pg.title(), pg.title())
    txt = pg.inner_text('body')
    bad = [x for x in ['100%', '3+', 'acedamic', '0108CS221042', 'â€', 'Ã', 'âœ', 'Â'] if x in txt]
    check('no fake stats / typo / mojibake in rendered text', not bad, bad)
    check('default theme is light', pg.evaluate("document.documentElement.dataset.theme") == 'light')
    pg.click('[data-theme-toggle]')
    check('theme toggles to dark', pg.evaluate("document.documentElement.dataset.theme") == 'dark')
    check('theme icon is SVG not emoji', pg.locator('.mv-theme .theme-icon svg').count() == 1)
    pg.reload()
    pg.wait_for_timeout(300)
    check('theme persists after reload', pg.evaluate("document.documentElement.dataset.theme") == 'dark')
    pg.screenshot(path='/home/claude/shots/home-dark-1366.png')
    pg.click('[data-theme-toggle]')
    for sec, label in [('lookup', 'Verify Result'), ('tools', 'Academic Tools'), ('history', 'History'), ('about', 'About'), ('hero', 'Home')]:
        pg.click(f'#nav-links a[data-section="{sec}"]')
        pg.wait_for_timeout(900)
        act = pg.evaluate("document.querySelector('.nav-link.active')?.dataset.section")
        check(f'nav "{label}" scrolls and activates', act == sec, f'active={act}')
    pg.click('[data-open-tool="cgpa"]')
    pg.wait_for_timeout(500)
    check('quick card opens CGPA tab', pg.evaluate("document.querySelector('[data-tool-tab=cgpa]').classList.contains('active')"))
    pg.evaluate("document.getElementById('lookup').scrollIntoView()")
    pg.wait_for_timeout(400)
    pg.click('#submit-btn')
    pg.wait_for_timeout(200)
    check('empty enrollment shows error', pg.is_visible('#enrollment-error'), pg.inner_text('#enrollment-error'))
    pg.fill('#enrollment-input', 'abc')
    pg.click('#submit-btn')
    check('invalid enrollment rejected', pg.is_visible('#enrollment-error'), pg.inner_text('#enrollment-error'))
    pg.fill('#enrollment-input', 'btit24o1040')
    pg.press('#enrollment-input', 'Tab')
    pg.wait_for_timeout(1200)
    check('input uppercased', pg.input_value('#enrollment-input') == 'BTIT24O1040')
    bi = pg.inner_text('#batch-info') if pg.is_visible('#batch-info') else ''
    check('batch detected and shown', '2024' in bi, repr(bi))
    opts = pg.eval_on_selector_all('#semester-select option', 'o=>o.map(x=>[x.value,x.textContent])')
    check('semesters populated dynamically', len([o for o in opts if o[0]]) >= 1, f'{len(opts)} options, first={opts[:2]}')
    pg.select_option('#semester-select', index=1)
    pg.click('#submit-btn')
    pg.wait_for_timeout(200)
    check('missing captcha blocked', pg.is_visible('#captcha-error'), pg.inner_text('#captcha-error'))
    pg.click('[data-exam-type="Ex"]')
    check('Ex segment syncs hidden select', pg.input_value('#exam-type-select') == 'Ex')
    check('Ex segment aria-checked', pg.get_attribute('[data-exam-type="Ex"]', 'aria-checked') == 'true' and pg.get_attribute('[data-exam-type="Regular"]', 'aria-checked') == 'false')
    pg.press('[data-exam-type="Ex"]', 'ArrowLeft')
    check('keyboard arrow switches to Regular', pg.input_value('#exam-type-select') == 'Regular')
    c1 = ''.join(pg.evaluate('window.__cap'))
    pg.click('#captcha-refresh')
    pg.wait_for_timeout(150)
    c2 = ''.join(pg.evaluate('window.__cap'))
    check('captcha refresh produces a new code', len(c1) == 5 and len(c2) == 5 and c1 != c2, f'{c1}->{c2}')
    pg.fill('#captcha-input', 'WRONG')
    pg.click('#submit-btn')
    pg.wait_for_timeout(200)
    check('wrong captcha rejected', pg.is_visible('#captcha-error'))
    pg.click('[data-exam-type="Ex"]')
    code = ''.join(pg.evaluate('window.__cap'))
    pg.fill('#captcha-input', code)
    pg.click('#submit-btn')
    pg.wait_for_selector('#result-error:not([hidden])', timeout=90000)
    msg = pg.inner_text('#result-error-message')
    check('real backend request: honest error, no fabricated result', pg.is_hidden('#result-display') and len(msg) > 5, msg)
    body = json.loads(posts[-1])
    check('request carried examType=Ex and no sessionCode', body.get('examType') == 'Ex' and 'sessionCode' not in body, body)
    check('submit button restored after failure', pg.is_enabled('#submit-btn') and 'Verify and Fetch Result' in pg.inner_text('#submit-btn'))
    mock = {'success': True, 'message': 'ok', 'data': {'studentName': 'TEST STUDENT', 'enrollmentNumber': 'BTIT24O1040', 'batchYear': 2024, 'semester': 1, 'examType': 'Ex', 'attemptNumber': 2, 'sessionCode': '112025', 'sgpa': 7.5, 'status': 'Pass', 'subjects': [{'code': 'IT101', 'name': 'Maths', 'grade': 'AA', 'gradePoint': '9', 'isNonCredit': False, 'passed': True}, {'code': 'IT102', 'name': 'Physics', 'grade': 'FL', 'gradePoint': '0', 'isNonCredit': False, 'passed': False}], 'directUrl': 'https://iums.mitsgwalior.in/ViewSC.aspx?U2bJdzw70jtQ3d=BTIT24O1040&U3bJdzw70jtQ4d=1&U4bJdzw70jtQ5d=112025', 'fetchedAt': '2026-11-09T00:00:00Z'}}
    pg.route('**/api/results/fetch', lambda r: r.fulfill(status=200, content_type='application/json', body=json.dumps(mock)))
    code = ''.join(pg.evaluate('window.__cap'))
    pg.fill('#captcha-input', code)
    pg.click('#submit-btn')
    pg.wait_for_selector('#result-display:not([hidden])', timeout=10000)
    check('(mocked response) result renders', 'TEST STUDENT' in pg.inner_text('#result-display') and 'FL' in pg.inner_text('#subjects-body'))
    hist = pg.evaluate("JSON.parse(localStorage.getItem('mits_search_history')||'[]')")
    check('history saved with examType Ex', hist and hist[0].get('examType') == 'Ex', hist[:1])
    pg.screenshot(path='/home/claude/shots/result-1366.png')
    pg.click('#nav-links a[data-section="history"]')
    pg.wait_for_timeout(600)
    pg.click('#history-list .history-reuse')
    pg.wait_for_timeout(900)
    check('history restore re-selects Ex and segment', pg.input_value('#exam-type-select') == 'Ex' and pg.get_attribute('[data-exam-type="Ex"]', 'aria-checked') == 'true')
    ctx.close()

    ctx = b.new_context(viewport={'width': 390, 'height': 844})
    pg = ctx.new_page()
    pg.goto(BASE + '/')
    pg.wait_for_timeout(400)
    check('mobile: menu hidden initially', not pg.is_visible('#nav-links'))
    pg.click('#nav-toggle')
    check('mobile: menu opens', pg.is_visible('#nav-links') and pg.get_attribute('#nav-toggle', 'aria-expanded') == 'true')
    pg.screenshot(path='/home/claude/shots/mobile-menu-390.png')
    pg.keyboard.press('Escape')
    check('mobile: Escape closes menu', not pg.is_visible('#nav-links'))
    pg.click('#nav-toggle')
    pg.click('#nav-links a[data-section="tools"]')
    pg.wait_for_timeout(400)
    check('mobile: link click closes menu', not pg.is_visible('#nav-links'))
    pg.click('#nav-toggle')
    pg.mouse.click(200, 760)
    check('mobile: outside click closes menu', not pg.is_visible('#nav-links'))
    small = pg.evaluate("[...document.querySelectorAll('.btn,.btn-icon,.mv-seg-btn,.mv-burger')].filter(e=>e.offsetParent&&e.getBoundingClientRect().height<36).map(e=>e.className+':'+Math.round(e.getBoundingClientRect().height))")
    check('mobile touch targets >=36px', not small, small[:4])
    ctx.close()
    b.close()
bad = [r for r in res if not r[1]]
print(f'\nTOTAL {len(res)} PASS {len(res)-len(bad)} FAIL {len(bad)}')
json.dump(res, open('/home/claude/e2e.json', 'w'))
